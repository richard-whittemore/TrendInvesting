#!/usr/bin/env python3
"""Replay a synthetic month into an engine in dry-run, playing the adapter, and print its decision log.

    sudo -u ti-trader python3 feed-month.py --socket /run/ti-engine-trad-ira/engine.sock \\
        --log /var/lib/trend-investing/engines/trad-ira/<TI_RUN>.log \\
        --config /etc/trend-investing/engines/trad-ira.config \\
        --month cmd/engine/testdata/momentum-month.jsonl [--first-sequence 2]

The month (cmd/engine/testdata/momentum-month.jsonl, generated by cmd/engine's
TestTheMomentumMonthFixtureIsTheGeneratedOne) holds invented prices only, never
market data. Each line is one input without the run's identity: this stamps the
configuration hash and strategy version read from the engine's durable log
header (ADR 0027), the next sequence of the engine's one input stream (2 after
the configuration, 3 after an approval; cmd/engine/engine.go, "Wire contract"),
and the configuration's account in place of the month's placeholder, "trad-ira".
It never connects to IBKR, and it prints no account number: only each decision's
type and outcome (ADR 0028; Boost lesson L12). It stops at the first input the
engine refuses, naming it.
"""
import argparse
import hashlib
import json
import socket
import sys

PLACEHOLDER = "trad-ira"


def stamp(line, header, account, sequence):
    """The envelope for one month line: the run's identity, sequence and account stamped on it."""
    payload = line["payload"]
    if payload.get("account_id") == PLACEHOLDER:
        payload = dict(payload, account_id=account)
    raw = json.dumps(payload, separators=(",", ":"))
    return {"id": line["id"], "type": line["type"], "envelope_version": 1, "schema_version": line["schema_version"],
            "event_time": line["event_time"], "recorded_at": line["event_time"], "sequence": sequence,
            "source": "feed-month", "strategy_version": header["strategy_version"],
            "configuration_hash": header["configuration_hash"],
            "payload_hash": hashlib.sha256(raw.encode()).hexdigest(), "payload": json.loads(raw)}


def describe(decision):
    """One decision as a log line, naming no account: its type, and a decision's outcome and reason."""
    p = decision.get("payload") or {}
    if decision["type"] == "strategy.targets.decided":
        return "{} {} {} {}".format(p.get("session_period_end", ""), decision["type"], p.get("outcome", ""),
                                    p.get("withheld_reason", "")).rstrip()
    if decision["type"] == "risk.order.released":
        return "{} {} {} send {}".format(decision["type"], p.get("side", ""), p.get("instrument_id", ""),
                                         str(p.get("send")).lower())
    return decision["type"]


def feed(socket_path, log_path, config_path, month_path, first_sequence=2):
    """Send every line of the month to the engine at socket_path; return the decision log's lines."""
    with open(log_path) as f:
        header = json.loads(f.readline())
    with open(config_path) as f:
        account = json.load(f)["account_id"]
    sock = socket.socket(socket.AF_UNIX)
    sock.settimeout(30)
    sock.connect(socket_path)
    replies = sock.makefile()
    lines, sequence = [], first_sequence
    try:
        with open(month_path) as month:
            for raw_line in month:
                line = json.loads(raw_line)
                envelope = stamp(line, header, account, sequence)
                sock.sendall((json.dumps(envelope, separators=(",", ":")) + "\n").encode())
                frame = json.loads(replies.readline() or "{}")
                reply = frame.get("envelope")
                if not reply or reply.get("type") != "engine.decisions":
                    message = json.dumps(frame).replace(account, "<account>")
                    raise SystemExit("feed-month: the engine refused {}: {}".format(line["id"], message))
                # The decisions carry the last sequence this exchange recorded, after any operator input recorded
                # first; the next input continues it (cmd/engine/engine.go).
                sequence = reply["sequence"] + 1
                for d in reply["payload"].get("decisions") or []:
                    lines.append(describe(d))
    finally:
        sock.close()
    return lines


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--socket", required=True)
    parser.add_argument("--log", required=True, help="the engine's durable log, whose header names the run")
    parser.add_argument("--config", required=True, help="the configuration the engine was started with")
    parser.add_argument("--month", required=True, help="the synthetic month, one input a line")
    parser.add_argument("--first-sequence", type=int, default=2)
    args = parser.parse_args(argv)
    for line in feed(args.socket, args.log, args.config, args.month, args.first_sequence):
        print(line)


if __name__ == "__main__":
    sys.exit(main())
